    [Test]
    public async Task Should_compile_every_form_inside_a_method_without_errors_or_warnings()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var type = file.Type(Sample());
            using var method = type.Method(Other());
            method.Line("string? s = System.Environment.GetEnvironmentVariable(\"X\");");

            using (var lone = method.If("s is null"))
            {
                lone.Line("System.Console.WriteLine(1);");

                using (var each = lone.ForEach("var", "c", "\"ab\""))
                {
                    each.Line("System.Console.WriteLine(c);");
                }

                using (var loop = lone.For("var i = 0", "i < 2", "i++"))
                {
                    loop.Line("System.Console.WriteLine(i);");
                }

                using (var wh = lone.While("s is null && System.Environment.ProcessorCount < 0"))
                {
                    wh.Line("break;");
                }

                using (var us = lone.Using("var ms = new System.IO.MemoryStream()"))
                {
                    us.Line("ms.WriteByte(1);");
                }

                using (var inner = lone.If("System.Environment.ProcessorCount > 0"))
                {
                    inner.Line("System.Console.WriteLine(2);");
                }
            }

            using (var ifElse = method.If("s is null"))
            {
                ifElse.Line("System.Console.WriteLine(1);");

                using var otherwise = ifElse.Else();
                otherwise.Line("System.Console.WriteLine(s.Length);");
            }

            using (var chain = method.If("s is null"))
            {
                chain.Line("System.Console.WriteLine(1);");

                using var second = chain.ElseIf("s.Length == 0");
                second.Line("System.Console.WriteLine(2);");

                using var third = second.ElseIf("s.Length == 1");
                third.Line("System.Console.WriteLine(3);");

                using var last = third.Else();
                last.Line("System.Console.WriteLine(4);");

                using var nested = last.If("s.Length > 5");
                nested.Line("System.Console.WriteLine(5);");

                using var nestedElse = nested.Else();
                nestedElse.Line("System.Console.WriteLine(6);");
            }
        }

        CSharpCompilation compilation = CompilationHelper.Compile(
            "public partial class Sample { }\n" + writer,
            allowErrors: true);

        string[] problems = compilation
            .GetDiagnostics()
            .Where(d => d.Severity is DiagnosticSeverity.Error or DiagnosticSeverity.Warning)
            .Select(d => d.ToString())
            .ToArray();

        await Assert.That(problems).IsEmpty();
    }

