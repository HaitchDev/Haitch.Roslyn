    private static async Task AssertRejectedWithoutWriting(Action<BodyScope> open)
    {
        SourceWriter writer = new();
        string before = null!;

        await Assert
            .That(() =>
            {
                using var file = writer.File();
                using var type = file.Type(Sample());
                using var method = type.Method(Other());
                before = writer.ToString();
                open(method);
            })
            .Throws<ArgumentException>();

        await Assert.That(writer.ToString()).StartsWith(before);
        await Assert.That(writer.ToString()).DoesNotContain("stub");
        await Assert.That(writer.ToString()).DoesNotContain("foreach");
        await Assert.That(writer.ToString()).DoesNotContain("while");
        await Assert.That(writer.ToString()).DoesNotContain("using (");
        await Assert.That(writer.ToString()).DoesNotContain("for (");
    }
