using Haitch.Roslyn.Models;
using Haitch.Roslyn.Tests.Models;
using Haitch.Roslyn.Writing;

namespace Haitch.Roslyn.Tests.Writing.Scopes;

public class FileAndNamespaceScopeTests
{
    private static TypeModel ModelOf(string source, string metadataName)
    {
        return TypeModel.From(CompilationHelper.GetNamedTypeSymbol(source, metadataName));
    }

    [Test]
    public async Task Should_render_header_and_a_namespace_block()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using (file.Namespace("A.B")) { }
        }

        string expected = """
            // <auto-generated/>
            #nullable enable

            namespace A.B
            {
            }

            """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
    }

    [Test]
    public async Task Should_render_using_directives_before_the_namespace()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            file.Using("System");
            using (file.Namespace("A")) { }
        }

        string expected = """
            // <auto-generated/>
            #nullable enable

            using System;

            namespace A
            {
            }

            """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
    }

    [Test]
    public async Task Should_render_sibling_namespaces_in_order()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using (file.Namespace("A")) { }

            using (file.Namespace("B")) { }
        }

        await Assert.That(writer.ToString()).Contains("namespace A\n{\n}\n\nnamespace B\n{\n}\n");
    }

    [Test]
    public async Task Should_close_a_namespace_only_once_when_disposed_twice()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            NamespaceScope scope = file.Namespace("A");
            scope.Dispose();
            scope.Dispose();
        }

        await Assert.That(writer.ToString()).EndsWith("namespace A\n{\n}\n");
    }

    [Test]
    public async Task Should_compile_a_legal_scope_snippet()
    {
        string[] errors = ScopeCompileCheck.Compile(
            """
                    using var file = writer.File();
                    using (file.Namespace("A.B"))
                    {
                    }
            """
        );

        await Assert.That(errors).IsEmpty();
    }

    [Test]
    public async Task Should_reject_a_namespace_nested_in_a_namespace()
    {
        string[] errors = ScopeCompileCheck.Compile(
            """
                    using var file = writer.File();
                    file.Namespace("A").Namespace("B");
            """
        );

        await Assert.That(errors).IsEquivalentTo(new[] { "CS1061" });
    }

    [Test]
    [Arguments(null)]
    [Arguments("")]
    [Arguments("  ")]
    public async Task Should_reject_a_blank_namespace_name(string? name)
    {
        SourceWriter writer = new();

        await Assert
            .That(() =>
            {
                using var file = writer.File();
                file.Namespace(name!);
            })
            .Throws<ArgumentException>();
    }

    [Test]
    public async Task Should_write_a_global_namespace_type_in_at_file_level()
    {
        TypeModel model = ModelOf("public class Global { }", "Global");

        SourceWriter actual = new();

        using (var file = actual.File())
        {
            using (file.TypeIn(model)) { }
        }

        SourceWriter expected = new();

        using (var file = expected.File())
        {
            using (file.Type(model)) { }
        }

        await Assert.That(actual.ToString()).IsEqualTo(expected.ToString());
    }

    [Test]
    public async Task Should_write_a_namespaced_type_in_its_namespace_block()
    {
        TypeModel model = ModelOf("namespace A.B { public class Plain { } }", "A.B.Plain");

        await Assert.That(WrittenIn(model)).IsEqualTo(WrittenInNamespace(model));
    }

    [Test]
    public async Task Should_write_a_containing_type_in_its_namespace_block()
    {
        TypeModel model = ModelOf(
            "namespace A { public class Outer<T> { public class Inner { } } }",
            "A.Outer`1+Inner"
        );

        await Assert.That(WrittenIn(model)).IsEqualTo(WrittenInNamespace(model));
    }

    [Test]
    public async Task Should_reject_a_file_local_type_in_before_writing_its_namespace()
    {
        TypeModel model = ModelOf("namespace A { public class Plain { } }", "A.Plain") with
        {
            IsFileLocal = true,
        };

        SourceWriter writer = new();

        await Assert
            .That(() =>
            {
                using var file = writer.File();
                file.TypeIn(model);
            })
            .Throws<ArgumentException>();

        await Assert.That(writer.ToString()).DoesNotContain("namespace");
    }

    [Test]
    public async Task Should_write_a_pending_attribute_on_a_namespaced_type_in_inside_its_namespace()
    {
        TypeModel model = ModelOf("namespace A { public class Plain { } }", "A.Plain");

        AttributeModel attribute = WellKnownAttributes.EditorBrowsableNever;

        await Assert
            .That(WrittenIn(model, attribute))
            .IsEqualTo(WrittenInNamespace(model, attribute));
    }

    [Test]
    public async Task Should_consume_pending_attributes_when_a_namespaced_type_in_is_rejected()
    {
        TypeModel model = ModelOf("namespace A { public class Plain { } }", "A.Plain") with
        {
            IsFileLocal = true,
        };

        SourceWriter writer = new();

        await Assert
            .That(() =>
            {
                using var file = writer.File();
                file.Attribute(WellKnownAttributes.EditorBrowsableNever).TypeIn(model);
            })
            .Throws<ArgumentException>();

        await Assert
            .That(writer.ToString())
            .IsEqualTo("// <auto-generated/>\n#nullable enable\n\n");
    }

    private static string WrittenIn(TypeModel model, AttributeModel? attribute = null)
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            file.Using("System");

            if (attribute is not null)
            {
                file.Attribute(attribute);
            }

            using (file.TypeIn(model)) { }
        }

        return writer.ToString();
    }

    private static string WrittenInNamespace(TypeModel model, AttributeModel? attribute = null)
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            file.Using("System");

            using (var ns = file.Namespace(model.Namespace!))
            {
                if (attribute is not null)
                {
                    ns.Attribute(attribute);
                }

                using (ns.Type(model)) { }
            }
        }

        return writer.ToString();
    }
}
