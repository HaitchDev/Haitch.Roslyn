    [Test]
    public async Task Should_compile_the_generated_file_with_attributes_on_every_position_without_diagnostics()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            file.Attribute(Generated);
            using (file.Type(TypeNamed("Outer"))) { }

            using var ns = file.Namespace("Example");
            ns.Attribute(Generated).Attribute(Browsable);
            using var type = ns.Type(TypeNamed("Sample"));

            type.Attribute(Generated);
            using (type.Method(MethodFrom("M"))) { }

            type.Attribute(Generated);
            type.Field(FieldFrom("Plain"));

            type.Attribute(Generated);
            type.AutoProperty(PropertyFrom("Count"));

            type.Attribute(Generated);

            using (var property = type.Property(PropertyFrom("Prop")))
            {
                using var get = property.Get();
                get.Line("return 0;");
            }

            type.Attribute(Browsable);
            using (type.Type(TypeNamed("Inner"))) { }
        }

        string source = "public partial class Outer { }\nnamespace Example { public partial class Sample { } }\n" +
                        writer;
        CSharpCompilation compilation = CompilationHelper.Compile(source, allowErrors: true);
        string[] diagnostics = compilation
            .GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning)
            .Select(diagnostic => diagnostic.Id)
            .ToArray();

        await Assert.That(string.Join(",", diagnostics)).IsEqualTo(string.Empty);
    }

    [Test]
    public async Task Should_reject_an_attribute_on_a_body_scope()
    {
        string[] errors = ScopeCompileCheck.Compile(
            """
                    Haitch.Roslyn.Models.TypeModel type = null!;
                    Haitch.Roslyn.Models.MethodModel method = null!;
                    Haitch.Roslyn.Models.AttributeModel attribute = null!;
                    using var file = writer.File();
                    using var t = file.Type(type);
                    using var body = t.Method(method);
                    body.Attribute(attribute);
            """);

        await Assert.That(errors).IsEquivalentTo(new[] { "CS1061" });
    }

    [Test]
    public async Task Should_compile_a_legal_attribute_chain_snippet()
    {
        string[] errors = ScopeCompileCheck.Compile(
            """
                    Haitch.Roslyn.Models.TypeModel type = null!;
                    Haitch.Roslyn.Models.AttributeModel attribute = null!;
                    using var file = writer.File();
                    using var ns = file.Namespace("A");
                    ns.Attribute(attribute).Attribute(attribute);
                    using var t = ns.Type(type);
                    t.Attribute(attribute).Attribute(attribute);
                    using (t.Type(type))
                    {
                    }
            """);

        await Assert.That(errors).IsEmpty();
    }
