    [Test]
    public async Task Should_write_an_attribute_above_each_member_kind_and_a_nested_type()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var type = file.Type(TypeNamed("Sample"));

            type.Attribute(Generated);
            using (type.Method(MethodFrom("M"))) { }

            type.Attribute(Generated);
            type.Field(FieldFrom("Plain"));

            type.Attribute(Generated);
            type.AutoProperty(PropertyFrom("Count"));

            type.Attribute(Generated);

            using (var property = type.Property(PropertyFrom("Prop")))
            {
                using var get = property.Get();
                get.Line("return 0;");
            }

            type.Attribute(Generated);
            using (type.Type(TypeNamed("Inner"))) { }
        }

        string expected =
            $$"""
              // <auto-generated/>
              #nullable enable

              partial class Sample
              {
                  {{GeneratedLine}}
                  public void M()
                  {
                  }

                  {{GeneratedLine}}
                  public int Plain;

                  {{GeneratedLine}}
                  public int Count { get; private set; }

                  {{GeneratedLine}}
                  public int Prop
                  {
                      get
                      {
                          return 0;
                      }
                  }

                  {{GeneratedLine}}
                  partial class Inner
                  {
                  }
              }

              """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
    }

