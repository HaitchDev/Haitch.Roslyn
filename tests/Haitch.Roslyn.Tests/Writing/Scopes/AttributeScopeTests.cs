    [Test]
    public async Task Should_leave_the_writer_untouched_when_the_method_header_cannot_be_rendered()
    {
        MethodModel method = MethodFrom("M");
        ParameterModel parameter = new(
            "p",
            TypeRef.From(CompilationHelper.GetNamedTypeSymbol("public class P { }", "P")),
            RefKind.None,
            ScopedKind.None,
            false,
            ConstantValue.Error,
            false,
            default);
        MethodModel unrenderable = method with { Parameters = new[] { parameter }.ToEquatableArray() };
        SourceWriter writer = new();

        await Assert
            .That(() =>
            {
                using var file = writer.File();
                using var type = file.Type(TypeNamed("Sample"));
                type.Attribute(Generated);
                type.Method(unrenderable);
            })
            .Throws<ArgumentException>();

        await Assert.That(writer.ToString()).IsEqualTo(EmptySampleFile);
    }

