    private const string MemberSource =
        """
        public abstract class Source
        {
            public void M() { }
            public abstract void Abstract();
            public int Plain;
            public int Count { get; private set; }
            public int Prop { get; set; }
        }
        """;

    private const string EmptySampleFile = "// <auto-generated/>\n#nullable enable\n\npartial class Sample\n{\n}\n";

    private const string EmptyNamespaceFile = "// <auto-generated/>\n#nullable enable\n\nnamespace A\n{\n}\n";

    private const string EmptyFile = "// <auto-generated/>\n#nullable enable\n\n";

    private const string GeneratedLine =
        "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"Tool\", \"1.0.0\")]";

    private const string BrowsableLine =
        "[global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Never)]";

    private static AttributeModel Generated => WellKnownAttributes.GeneratedCode("Tool", "1.0.0");

    private static AttributeModel Browsable => WellKnownAttributes.EditorBrowsableNever;

    private static TypeModel TypeNamed(string name)
    {
        return TypeModel.From(CompilationHelper.GetNamedTypeSymbol($"public partial class {name} {{ }}", name));
    }

    private static MethodModel MethodFrom(string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, "Source");

        return MethodModel.From(type.GetMembers(name).OfType<IMethodSymbol>().Single());
    }

    private static FieldModel FieldFrom(string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, "Source");

        return FieldModel.From(type.GetMembers(name).OfType<IFieldSymbol>().Single());
    }

    private static PropertyModel PropertyFrom(string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, "Source");

        return PropertyModel.From(type.GetMembers(name).OfType<IPropertySymbol>().Single());
    }

    [Test]
    public async Task Should_write_two_attributes_directly_above_a_type_in_a_namespace()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var ns = file.Namespace("Example");
            ns.Attribute(Generated).Attribute(Browsable);
            using (ns.Type(TypeNamed("Sample"))) { }
        }

        string expected =
            $$"""
              // <auto-generated/>
              #nullable enable

              namespace Example
              {
                  {{GeneratedLine}}
                  {{BrowsableLine}}
                  partial class Sample
                  {
                  }
              }

              """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
    }

