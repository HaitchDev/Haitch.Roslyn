    [Test]
    [Arguments(Accessibility.Protected)]
    [Arguments(Accessibility.ProtectedOrInternal)]
    [Arguments(Accessibility.ProtectedAndInternal)]
    public async Task Should_reject_a_protected_new_type_inside_a_struct_or_a_static_class(Accessibility accessibility)
    {
        NewTypeModel[] containers =
        [
            new("S", TypeDeclarationKind.Struct, Accessibility.Public),
            new("R", TypeDeclarationKind.RecordStruct, Accessibility.Public),
            new("C", TypeDeclarationKind.Class, Accessibility.Public) { IsStatic = true },
        ];

        foreach (NewTypeModel container in containers)
        {
            SourceWriter writer = new();
            string before;
            string after;
            var threw = false;

            using (var file = writer.File())
            {
                using var scope = file.NewType(container);
                scope.Field(FieldFrom("Plain") with { IsStatic = true });
                before = writer.ToString();

                try
                {
                    scope.NewType(new NewTypeModel("Inner", TypeDeclarationKind.Class, accessibility));
                }
                catch (ArgumentException)
                {
                    threw = true;
                }

                after = writer.ToString();
            }

            await Assert.That(threw).IsTrue();
            await Assert.That(after).IsEqualTo(before);
        }
    }

