    [Test]
    public async Task Should_write_a_new_type_nested_in_a_new_type_and_compile()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var ns = file.Namespace("Example");
            ns.NewType(new NewTypeModel("A", TypeDeclarationKind.Class, Accessibility.Public)).Dispose();

            using var outer = ns.NewType(new NewTypeModel("Outer", TypeDeclarationKind.Class, Accessibility.Public));
            outer.Field(FieldFrom("Plain"));
            using var inner = outer.NewType(
                new NewTypeModel("Inner", TypeDeclarationKind.Struct, Accessibility.Protected));
            inner.AutoProperty(PropertyFrom("Count"));
            using (inner.Method(MethodFrom("Source", "M"))) { }

            using var innermost = inner.NewType(
                new NewTypeModel("Innermost", TypeDeclarationKind.Interface, Accessibility.Public));
            using (innermost.Method(MethodFrom("ISource", "Default"))) { }
        }

        await AssertCompiles(writer.ToString());
    }

