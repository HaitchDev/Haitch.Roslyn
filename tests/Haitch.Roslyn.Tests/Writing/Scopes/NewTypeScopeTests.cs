    private const string MemberSource =
        """
        public abstract class Source
        {
            public void M() { }
            public int Plain;
            public int Count { get; private set; }
            public int Prop { get; set; }
        }

        public interface ISource
        {
            void Default() { }
            int InstanceField => 0;
        }
        """;

    private static TypeModel TypeNamed(string name)
    {
        return TypeModel.From(CompilationHelper.GetNamedTypeSymbol($"public partial class {name} {{ }}", name));
    }

    private static MethodModel MethodFrom(string typeName, string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, typeName);

        return MethodModel.From(type.GetMembers(name).OfType<IMethodSymbol>().Single());
    }

    private static FieldModel FieldFrom(string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, "Source");

        return FieldModel.From(type.GetMembers(name).OfType<IFieldSymbol>().Single());
    }

    private static PropertyModel PropertyFrom(string name)
    {
        INamedTypeSymbol type = CompilationHelper.GetNamedTypeSymbol(MemberSource, "Source");

        return PropertyModel.From(type.GetMembers(name).OfType<IPropertySymbol>().Single());
    }

    private static async Task AssertCompiles(string output)
    {
        CSharpCompilation compilation = CompilationHelper.Compile(output, allowErrors: true);
        string[] problems = compilation
            .GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity is DiagnosticSeverity.Error or DiagnosticSeverity.Warning)
            .Select(diagnostic => diagnostic.ToString())
            .ToArray();

        await Assert.That(problems).IsEmpty();
    }

    [Test]
    public async Task Should_write_a_new_class_in_a_namespace_with_a_field_method_and_property()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var ns = file.Namespace("Example");
            using var type = ns.NewType(new NewTypeModel("Widget", TypeDeclarationKind.Class, Accessibility.Public));
            type.Field(FieldFrom("Plain"));
            using (type.Method(MethodFrom("Source", "M"))) { }

            type.AutoProperty(PropertyFrom("Count"));
        }

        string expected =
            """
            // <auto-generated/>
            #nullable enable

            namespace Example
            {
                public class Widget
                {
                    public int Plain;

                    public void M()
                    {
                    }

                    public int Count { get; private set; }
                }
            }

            """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
        await AssertCompiles(writer.ToString());
    }

