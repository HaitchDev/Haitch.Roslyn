    [Test]
    [Arguments(Accessibility.Private)]
    [Arguments(Accessibility.Protected)]
    [Arguments(Accessibility.ProtectedOrInternal)]
    [Arguments(Accessibility.ProtectedAndInternal)]
    public async Task Should_reject_a_nested_only_accessibility_for_a_top_level_new_type(Accessibility accessibility)
    {
        NewTypeModel model = new("Widget", TypeDeclarationKind.Class, accessibility);

        SourceWriter fileWriter = new();
        string fileBefore;
        string fileAfter;
        var fileThrew = false;

        using (var file = fileWriter.File())
        {
            file.Using("System");
            fileBefore = fileWriter.ToString();

            try
            {
                file.NewType(model);
            }
            catch (ArgumentException)
            {
                fileThrew = true;
            }

            fileAfter = fileWriter.ToString();
        }

        SourceWriter namespaceWriter = new();
        string namespaceBefore;
        string namespaceAfter;
        var namespaceThrew = false;

        using (var file = namespaceWriter.File())
        {
            using var ns = file.Namespace("Example");
            using (ns.NewType(new NewTypeModel("First", TypeDeclarationKind.Class, Accessibility.Public))) { }

            namespaceBefore = namespaceWriter.ToString();

            try
            {
                ns.NewType(model);
            }
            catch (ArgumentException)
            {
                namespaceThrew = true;
            }

            namespaceAfter = namespaceWriter.ToString();
        }

        await Assert.That(fileThrew).IsTrue();
        await Assert.That(fileAfter).IsEqualTo(fileBefore);
        await Assert.That(namespaceThrew).IsTrue();
        await Assert.That(namespaceAfter).IsEqualTo(namespaceBefore);
    }

