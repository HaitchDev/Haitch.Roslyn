    [Test]
    public async Task Should_write_a_sealed_class_nested_in_a_partial_type_scope()
    {
        SourceWriter writer = new();

        using (var file = writer.File())
        {
            using var outer = file.Type(TypeNamed("Outer"));
            outer.Field(FieldFrom("Plain"));
            using var inner = outer.NewType(
                new NewTypeModel("Inner", TypeDeclarationKind.Class, Accessibility.Private) { IsSealed = true });
            inner.AutoProperty(PropertyFrom("Count"));
        }

        string expected =
            """
            // <auto-generated/>
            #nullable enable

            partial class Outer
            {
                public int Plain;

                private sealed class Inner
                {
                    public int Count { get; private set; }
                }
            }

            """;

        await Assert.That(writer.ToString()).IsEqualTo(expected);
        await AssertCompiles("public partial class Outer { }\n" + writer);
    }

